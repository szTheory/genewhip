#!/usr/bin/env python3
"""Generate an original windowed-sinc band-limited-step interpolation table.

The table follows the published band-limited-step method: window a sampled sinc,
normalise its impulse response, integrate it, then sample the cumulative response
at fixed fractional phases. No blip_buf or Genesis Plus GX code or tables were
consulted. Values are in output-sample units with a Q20 scale.
"""
# SPDX-License-Identifier: MIT
import argparse
import math
from pathlib import Path

PHASES = 64
TAPS = 16
SCALE = 1 << 20


def sinc(x):
    if abs(x) < 1e-15:
        return 1.0
    return math.sin(math.pi * x) / (math.pi * x)


def generate():
    rows = []
    center = (TAPS - 1) / 2.0
    for phase in range(PHASES):
        fraction = phase / PHASES
        impulse = []
        for tap in range(TAPS):
            x = tap - center - fraction
            window = 0.42 - 0.5 * math.cos(2.0 * math.pi * tap / (TAPS - 1)) + 0.08 * math.cos(4.0 * math.pi * tap / (TAPS - 1))
            impulse.append(sinc(x) * window)
        total = sum(impulse)
        cumulative = 0.0
        row = []
        for value in impulse:
            cumulative += value / total
            row.append(round(cumulative * SCALE))
        row[-1] = SCALE
        rows.append(row)
    return rows


def render():
    lines = [
        "/* SPDX-License-Identifier: MIT */",
        "/* Generated by tools/audio/gen_kernel.py; do not edit by hand. Q20 output-sample units. */",
        "#ifndef GW_AUDIO_KERNEL_H",
        "#define GW_AUDIO_KERNEL_H",
        "#include <stdint.h>",
        f"#define GW_BLEP_PHASES {PHASES}u",
        f"#define GW_BLEP_TAPS {TAPS}u",
        f"#define GW_BLEP_SCALE INT32_C({SCALE})",
        "static const int32_t gw_blep_kernel[GW_BLEP_PHASES][GW_BLEP_TAPS] = {",
    ]
    for row in generate():
        lines.append("    {" + ", ".join(str(value) for value in row) + "},")
    lines += ["};", "#endif", ""]
    return "\n".join(lines).encode("ascii")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[2] / "src/audio_kernel.h")
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(render())


if __name__ == "__main__":
    main()
