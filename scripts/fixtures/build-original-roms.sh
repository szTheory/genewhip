#!/bin/bash
# Reproducible builds of original GNU as ROM sources with the pinned assembler.
#   --self-test                      build an inline source twice, print its digest
#   --update NAME                    build NAME twice and write the committed ROM
#   --verify-reproducible [NAME...]  build twice and compare with the committed ROM
# NAME maps to tests/devices/roms/NAME.s -> NAME.bin (1024 bytes) unless an
# original-rom row in fixtures/manifest.json with build.name == NAME gives
# source, rom and rom_bytes.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/../.." && pwd -P)
MANIFEST="$ROOT/fixtures/manifest.json"
EXTRACT="$ROOT/scripts/fixtures/original_rom.py"
DEFAULT_BYTES=1024
blocked() { printf 'BLOCKED: %s\n' "$*" >&2; exit 1; }
fail() { printf 'FAIL: %s\n' "$*" >&2; exit 1; }

# Print "source<TAB>rom<TAB>bytes" for NAME.
resolve() {
  python3 -I - "$MANIFEST" "$1" <<'PY'
import json, sys
manifest, name = sys.argv[1:]
rows = [r for r in json.load(open(manifest))["fixtures"]
        if r.get("kind") == "original-rom" and r.get("build", {}).get("name") == name]
if len(rows) > 1:
    raise SystemExit("FAIL: duplicate original-rom rows for " + name)
if rows:
    r = rows[0]
    print("%s\t%s\t%d" % (r["source"], r["rom"], r["rom_bytes"]))
else:
    print("tests/devices/roms/%s.s\ttests/devices/roms/%s.bin\t1024" % (name, name))
PY
}

list_names() {
  python3 -I - "$MANIFEST" <<'PY'
import json, sys
for r in json.load(open(sys.argv[1]))["fixtures"]:
    if r.get("kind") == "original-rom":
        print(r["build"]["name"])
PY
}

# Build the optional manifest Z80 stage before assembling the enclosing ROM.
# Verify mode compares the generated include without changing tracked files.
prepare_z80() {
  local name=$1 mode=$2 line zsrc zinc as tmp n
  line=$(python3 -I - "$MANIFEST" "$name" <<'PY'
import json, pathlib, sys
rows = [r for r in json.load(open(sys.argv[1]))['fixtures']
        if r.get('kind') == 'original-rom' and r.get('build', {}).get('name') == sys.argv[2]]
if len(rows) > 1:
    raise SystemExit('FAIL: duplicate original-rom rows')
b = rows[0].get('build', {}) if rows else {}
s, i = b.get('z80_source'), b.get('z80_include')
if s is None and i is None:
    print('-\t-')
else:
    for value in (s, i):
        if not isinstance(value, str) or not value or pathlib.PurePosixPath(value).is_absolute() or '..' in pathlib.PurePosixPath(value).parts or any(c in value for c in '\t\n\r'):
            raise SystemExit('FAIL: invalid Z80 stage path')
    print(s + '\t' + i)
PY
  ) || return 1
  IFS=$'\t' read -r zsrc zinc <<<"$line"
  [ "$zsrc" != - ] || return 0
  as=$(bash "$ROOT/scripts/fixtures/z80-as.sh") || blocked 'pinned z80 assembler unavailable'
  tmp=$(mktemp -d "${TMPDIR:-/tmp}/genewhip-z80-stage.XXXXXX")
  trap 'rm -rf "$tmp"' RETURN
  for n in one two; do
    mkdir "$tmp/$n"
    (cd "$tmp/$n" && "$as" -I "$ROOT" -o z80.o "$ROOT/$zsrc") || blocked "Z80 clean $n assembly failed"
    python3 -I "$EXTRACT" extract "$tmp/$n/z80.o" "$tmp/$n/z80.bin" auto --machine z80
  done
  cmp -s "$tmp/one/z80.bin" "$tmp/two/z80.bin" || fail 'clean Z80 builds differ'
  python3 -I - "$tmp/one/z80.bin" "$tmp/z80.inc" "$zsrc" <<'PY'
import hashlib, pathlib, sys
b = pathlib.Path(sys.argv[1]).read_bytes()
lines = ['/* generated by scripts/fixtures/build-original-roms.sh from ' + sys.argv[3] + '; sha256 ' + hashlib.sha256(b).hexdigest() + ' */']
lines += ['.byte ' + ', '.join('0x%02x' % x for x in b[i:i+16]) for i in range(0, len(b), 16)]
pathlib.Path(sys.argv[2]).write_text('\n'.join(lines) + '\n')
PY
  if [ "$mode" = verify ]; then
    cmp -s "$tmp/z80.inc" "$ROOT/$zinc" || fail 'z80 include differs'
  else
    mkdir -p "$(dirname "$ROOT/$zinc")"
    cp "$tmp/z80.inc" "$ROOT/$zinc"
  fi
}

check_vectors() {
  python3 -I - "$1" <<'PY'
import pathlib, struct, sys
b = pathlib.Path(sys.argv[1]).read_bytes()
if len(b) < 8 or len(b) & 1:
    raise SystemExit("FAIL: ROM image must be an even length of at least 8 bytes")
sp, pc = struct.unpack_from(">II", b, 0)
if sp & 1 or pc & 1:
    raise SystemExit("FAIL: reset vectors must be even")
if pc >= len(b):
    raise SystemExit("FAIL: reset PC lies outside the image")
PY
}

# build_twice SOURCE SIZE OUTFILE : two clean assemblies must agree byte for byte.
build_twice() {
  local src=$1 size=$2 out=$3 as tmp n
  as=$(bash "$ROOT/scripts/fixtures/m68k-as.sh") || blocked 'pinned assembler unavailable'
  [ -f "$src" ] || blocked "source missing: $src"
  tmp=$(mktemp -d "${TMPDIR:-/tmp}/genewhip-original-rom.XXXXXX")
  trap 'rm -rf "$tmp"' RETURN
  for n in one two; do
    mkdir "$tmp/$n"
    (cd "$tmp/$n" && "$as" -I "$ROOT" -o rom.o "$src") || blocked "clean $n assembly failed"
    python3 -I "$EXTRACT" extract "$tmp/$n/rom.o" "$tmp/$n/rom.bin" "$size"
  done
  cmp -s "$tmp/one/rom.bin" "$tmp/two/rom.bin" || fail "clean builds differ for $src"
  check_vectors "$tmp/one/rom.bin"
  cp "$tmp/one/rom.bin" "$out"
}

sha() { shasum -a 256 "$1" | awk '{print $1}'; }

self_test() {
  local tmp
  tmp=$(mktemp -d "${TMPDIR:-/tmp}/genewhip-original-selftest.XXXXXX")
  trap 'rm -rf "$tmp"' RETURN
  cat > "$tmp/selftest.s" <<'ASM'
/* SPDX-License-Identifier: MIT
 * Inline build-pipeline self-test image for Genewhip. */
        .cpu 68000
        .text
        .org    0x0000
        .long   0x00ffff00
        .long   0x00000200
        .org    0x0100
        .ascii  "SEGA MEGA DRIVE "
        .org    0x01f0
        .ascii  "JUE"
        .org    0x0200
start:  bra.s   start
ASM
  build_twice "$tmp/selftest.s" "$DEFAULT_BYTES" "$tmp/selftest.bin"
  python3 -I - "$tmp/selftest.bin" <<'PY'
import pathlib, sys
b = pathlib.Path(sys.argv[1]).read_bytes()
if b[0x100:0x104] != b"SEGA" or b[0x1f0:0x1f3] != b"JUE" or b[0x200:0x202] != b"\x60\xfe":
    raise SystemExit("FAIL: self-test image content is wrong")
PY
  printf 'original-roms self-test: PASS %s\n' "$(sha "$tmp/selftest.bin")"
}

paths_for() {
  local line
  line=$(resolve "$1") || exit 1
  IFS=$'\t' read -r R_SRC R_ROM R_BYTES <<<"$line"
  case "$R_SRC$R_ROM" in /*|*..*) fail "non-public path for $1" ;; esac
}

update() {
  local tmp
  paths_for "$1"
  prepare_z80 "$1" update
  tmp=$(mktemp "${TMPDIR:-/tmp}/genewhip-original-update.XXXXXX")
  build_twice "$ROOT/$R_SRC" "$R_BYTES" "$tmp" || { rm -f "$tmp"; exit 1; }
  mkdir -p "$(dirname "$ROOT/$R_ROM")"
  mv "$tmp" "$ROOT/$R_ROM"
  printf 'original-roms: updated %s %s\n' "$R_ROM" "$(sha "$ROOT/$R_ROM")"
}

verify() {
  local tmp name
  if [ "$#" -eq 0 ]; then
    set -- $(list_names)
    if [ "$#" -eq 0 ]; then printf 'original-roms: 0 rows\n'; return 0; fi
  fi
  for name in "$@"; do
    paths_for "$name"
    prepare_z80 "$name" verify
    [ -f "$ROOT/$R_ROM" ] || fail "committed ROM missing: $R_ROM"
    tmp=$(mktemp "${TMPDIR:-/tmp}/genewhip-original-verify.XXXXXX")
    build_twice "$ROOT/$R_SRC" "$R_BYTES" "$tmp" || { rm -f "$tmp"; exit 1; }
    cmp -s "$tmp" "$ROOT/$R_ROM" || { rm -f "$tmp"; fail "rebuilt bytes differ from committed $R_ROM"; }
    rm -f "$tmp"
    printf 'original-roms: %s reproducible %s\n' "$name" "$(sha "$ROOT/$R_ROM")"
  done
}

case "${1:-}" in
  --self-test) self_test ;;
  --update) [ -n "${2:-}" ] || blocked 'usage: --update NAME'; update "$2" ;;
  --verify-reproducible) shift; verify "$@" ;;
  *) blocked "usage: $0 --self-test | --update NAME | --verify-reproducible [NAME...]" ;;
esac
